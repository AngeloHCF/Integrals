"""Bundle the course worksheet and preserve the original worksheet and its IDs."""
import json
import re
from pathlib import Path
from course_content import PROBLEMS

ROOT = Path(__file__).resolve().parents[1]

def read_group(text, start):
    assert text[start] == '{'
    depth = 1
    end = start + 1
    while depth:
        if text[end] == '{' and text[end - 1] != '\\':
            depth += 1
        elif text[end] == '}' and text[end - 1] != '\\':
            depth -= 1
        end += 1
    return text[start + 1:end - 1], end

def source_problems():
    source = (ROOT / 'main.tex').read_text(encoding='utf-8')
    problems = []
    for match in re.finditer(r'\\question\{ans\d+\}', source):
        position = match.start() + len('\\question')
        values = []
        for _ in range(3):
            value, position = read_group(source, position)
            values.append(value)
        problems.append(dict(zip(('id', 'question', 'answer'), values)))
    assert [p['id'] for p in problems] == [f'ans{i}' for i in range(1, 101)]
    return problems

def build():
    steps = {}
    for filename in ('steps-1-50.json', 'steps-51-100.json'):
        steps.update(json.loads((ROOT / 'worksheet' / filename).read_text(encoding='utf-8-sig')))
    problems = source_problems()
    assert set(steps) == {p['id'] for p in problems}
    for problem in problems:
        worked = steps[problem['id']]
        assert worked['method'] and len(worked['steps']) >= 3, problem['id']
        assert all(step.get('text') for step in worked['steps']), problem['id']
        problem.update(worked)
        problem['answer'] += ' + C'
    course = [{k:v for k,v in p.items() if k != 'check'} for p in PROBLEMS]
    sets = {
        'course': {
            'storagePrefix': 'integrals.course-v1.',
            'subtitle': '10 course topics · 100 practice problems',
            'instructions': 'Solve each problem, showing your method. Include $C$ for indefinite integrals. For improper integrals, justify convergence or divergence.',
            'footer': '70 medium · 20 hard · 10 tricky · Worked solutions for every question.',
            'problems': course,
        },
        'original': {
            'storagePrefix': 'integrals.worksheet.',
            'subtitle': 'Original integration techniques · 100 practice problems',
            'instructions': 'Evaluate each indefinite integral. Include the constant of integration $C$ in every answer.',
            'footer': 'Your original 100 questions, notes, and checkmarks are preserved here.',
            'problems': problems,
        },
    }
    output = '// Generated by scripts/build_worksheet.py. See README for content sources.\n'
    output += 'window.WORKSHEETS = ' + json.dumps(sets, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'worksheet' / 'problems.js').write_text(output, encoding='utf-8')
    print(f'Built {len(course)} course problems; retained {len(problems)} original problems with unchanged storage IDs.')

if __name__ == '__main__':
    build()
